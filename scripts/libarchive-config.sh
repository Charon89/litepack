#!/usr/bin/env bash
# Generates the config.h LitePack compiles libarchive with, for one target, with libarchive's own CMake (E4-4, R203).
#   scripts/libarchive-config.sh <target> <libarchive source dir> <out file>
# <target> is x86_64-unknown-linux-gnu, x86_64-pc-windows-msvc or aarch64-pc-windows-msvc. The source dir is the
# extracted release named in scripts/libarchive-release.env (read only: CMake builds in a temporary folder). The
# committed files are vendor/libarchive-<version>/litepack-config/<target>/config.h; the workflow
# .github/workflows/libarchive-config.yml runs this script on each target's runner and diffs. To move to a new
# libarchive version: edit scripts/libarchive-release.env, vendor the new files, run the workflow, and copy the
# generated files from its log (docs: vendor/libarchive-*/LITEPACK-CHANGES.md).
# Environment: CMAKE (path of cmake, default `cmake`); LPK_CMAKE_GENERATOR (override the Visual Studio generator).
set -euo pipefail

if [[ $# -ne 3 ]]; then
  echo "usage: $0 <target> <libarchive source dir> <out file>" >&2
  exit 2
fi
target="$1"
src="$2"
out="$3"
here="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=libarchive-release.env
source "$here/libarchive-release.env"
cmake="${CMAKE:-cmake}"

[[ -f "$src/CMakeLists.txt" ]] || { echo "no CMakeLists.txt in $src" >&2; exit 2; }
number="$(printf '%d%03d%03d' "${LIBARCHIVE_VERSION%%.*}" "$(echo "$LIBARCHIVE_VERSION" | cut -d. -f2)" "$(echo "$LIBARCHIVE_VERSION" | cut -d. -f3)")"
have="$(tr -d '[:space:]' < "$src/build/version" 2>/dev/null || true)"
[[ "$have" == "$number" ]] || { echo "$src is not libarchive $LIBARCHIVE_VERSION (build/version is not $number)" >&2; exit 2; }

gen_args=()
case "$target" in
  x86_64-unknown-linux-gnu)
    ;;
  x86_64-pc-windows-msvc | aarch64-pc-windows-msvc)
    arch=x64
    [[ "$target" == aarch64-* ]] && arch=ARM64
    if [[ -n "${LPK_CMAKE_GENERATOR:-}" ]]; then
      gen="$LPK_CMAKE_GENERATOR"
    else
      # Newest Visual Studio generator this CMake knows, preferring 17 2022.
      gen="Visual Studio 17 2022"
      if ! "$cmake" --help | grep -q "$gen"; then
        gen="$("$cmake" --help | grep -o 'Visual Studio [0-9]* [0-9]*' | sort -u | sort -k3 -n | tail -n 1)"
      fi
    fi
    echo "libarchive-config: generator '$gen', platform $arch" >&2
    gen_args=(-G "$gen" -A "$arch")
    ;;
  *)
    echo "unknown target $target" >&2
    exit 2
    ;;
esac

# Read-only build: no tools, no tests, no writers' dependencies. Every optional library is OFF so that nothing a
# runner has installed leaks into the file; the three codecs are added below by hand (they come from libz-sys,
# liblzma-sys and zstd-sys).
options=(
  -DENABLE_TEST=OFF -DENABLE_TAR=OFF -DENABLE_CPIO=OFF -DENABLE_CAT=OFF -DENABLE_UNZIP=OFF
  -DENABLE_INSTALL=OFF -DENABLE_OPENSSL=OFF -DENABLE_MD=OFF -DENABLE_BZip2=OFF -DENABLE_LZ4=OFF -DENABLE_LZO=OFF
  -DENABLE_ZLIB=OFF -DENABLE_LZMA=OFF -DENABLE_ZSTD=OFF
  -DENABLE_LIBXML2=OFF -DENABLE_BSDXML=OFF -DENABLE_EXPAT=OFF -DENABLE_WIN32_XMLLITE=OFF -DENABLE_CNG=OFF
  -DENABLE_NETTLE=OFF -DENABLE_MBEDTLS=OFF -DENABLE_LIBB2=OFF -DENABLE_PCREPOSIX=OFF -DENABLE_PCRE2POSIX=OFF
  -DENABLE_ICONV=OFF -DENABLE_ACL=OFF -DENABLE_XATTR=OFF -DENABLE_LIBGCC=OFF
  -DPOSIX_REGEX_LIB=NONE -DBUILD_SHARED_LIBS=OFF
)

build="$(mktemp -d)"
trap 'rm -rf "$build"' EXIT
"$cmake" -S "$src" -B "$build" "${gen_args[@]}" "${options[@]}" >&2
[[ -f "$build/config.h" ]] || { echo "CMake wrote no config.h" >&2; exit 1; }

{
  cat <<EOF
/* LitePack config.h for libarchive $LIBARCHIVE_VERSION, target $target (E4-4).
 *
 * Generated by libarchive's own CMake; do not edit. scripts/libarchive-config.sh makes it on the target's
 * runner, and .github/workflows/libarchive-config.yml fails when this file differs from what the script
 * generates (the job log prints the generated file). The release is pinned in scripts/libarchive-release.env.
 * CMake options (everything optional is off, so nothing installed on the runner leaks in):
 *   -DENABLE_TEST=OFF -DENABLE_TAR=OFF -DENABLE_CPIO=OFF -DENABLE_CAT=OFF -DENABLE_UNZIP=OFF
 *   -DENABLE_INSTALL=OFF -DENABLE_OPENSSL=OFF -DENABLE_MD=OFF -DENABLE_BZip2=OFF -DENABLE_LZ4=OFF
 *   -DENABLE_LZO=OFF -DENABLE_ZLIB=OFF -DENABLE_LZMA=OFF -DENABLE_ZSTD=OFF -DENABLE_LIBXML2=OFF
 *   -DENABLE_BSDXML=OFF -DENABLE_EXPAT=OFF -DENABLE_WIN32_XMLLITE=OFF -DENABLE_CNG=OFF
 *   -DENABLE_NETTLE=OFF -DENABLE_MBEDTLS=OFF -DENABLE_LIBB2=OFF -DENABLE_PCREPOSIX=OFF
 *   -DENABLE_PCRE2POSIX=OFF -DENABLE_ICONV=OFF -DENABLE_ACL=OFF -DENABLE_XATTR=OFF
 *   -DENABLE_LIBGCC=OFF -DPOSIX_REGEX_LIB=NONE -DBUILD_SHARED_LIBS=OFF
 * Windows targets: the Visual Studio generator with -A x64 or -A ARM64; Linux: CMake's default generator.
 * The text below the marker "LitePack additions" is the same for every target.
 */
EOF
  tr -d '\r' < "$build/config.h"
  cat <<'EOF'

/* ---- LitePack additions: the codecs come from libz-sys, liblzma-sys and zstd-sys ---- */
#define HAVE_LIBZ 1
#define HAVE_ZLIB_H 1
#define HAVE_LIBLZMA 1
#define HAVE_LZMA_H 1
#define HAVE_LIBZSTD 1
#define HAVE_ZSTD_H 1
EOF
} > "$out"
echo "libarchive-config: wrote $out" >&2
